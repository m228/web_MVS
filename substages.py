# группа порога муки → коды подстадий
GROUPS = {"pump": range(51, 60), "g1": (71, 72), "g2": range(73, 80)}
GROUP_TITLES = {"pump": "подкачка", "g1": "рост 1", "g2": "рост 2"}


def name_of(code) -> str | None:
    try:
        c = int(round(float(code)))
    except (TypeError, ValueError):
        return None
    return NAMES.get(c, "подстадия %d" % c)


def group_of(code) -> str | None:
    """pump / g1 / g2 или None (общий порог)."""
    try:
        c = int(round(float(code)))
    except (TypeError, ValueError):
        return None
    for g, codes in GROUPS.items():
        if c in codes:
            return g
    return None
